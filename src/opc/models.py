"""Typed domain models for the One-Person Company (OPC) platform."""
from __future__ import annotations

from dataclasses import dataclass, field
from decimal import Decimal
from enum import Enum
from typing import Any


class WorkflowStatus(str, Enum):
    """Lifecycle status of an OPC workflow run."""

    PENDING_APPROVAL = "pending_approval"
    APPROVED = "approved"
    REJECTED = "rejected"
    REVISE_REQUESTED = "revise_requested"
    COMPLETED = "completed"
    RECONCILIATION_REQUIRED = "reconciliation_required"
    FAILED = "failed"


class ApprovalDecision(str, Enum):
    """Human owner decision on a pending proposal/action."""

    APPROVE = "approve"
    REJECT = "reject"
    REVISE = "revise"


class UsageStage(str, Enum):
    """Honest economic lifecycle stage for resource usage."""

    ESTIMATED = "estimated"
    RESERVED = "reserved"
    ACTUAL = "actual"
    UNKNOWN = "unknown"


@dataclass(frozen=True)
class PackManifest:
    """Declarative pack manifest (opc-pack/v1)."""

    pack_id: str
    version: str
    schema_version: str
    owner: str
    license: str
    compatible_runtime: str
    workflow_id: str
    entrypoint: str
    input_schema: dict[str, Any]
    output_schema: dict[str, Any]
    connectors: tuple[str, ...]
    credential_refs: tuple[str, ...]
    capabilities: tuple[str, ...]
    permissions: tuple[str, ...]
    external_effects: tuple[str, ...]
    approval_required: bool
    cost_policy: dict[str, Any]
    languages: tuple[str, ...]
    jurisdiction: str = "global"
    pack_dir: str = ""


@dataclass(frozen=True)
class BusinessProfile:
    """Owner's minimal OPC business profile."""

    business_name: str
    owner_name: str
    language: str
    locale: str
    timezone: str
    currency: str
    services: dict[str, Decimal]
    payment_terms: str
    jurisdiction: str = "global"
    preferences: dict[str, Any] = field(default_factory=dict)


@dataclass(frozen=True)
class ProposalInput:
    """Structured client request intake."""

    request_id: str
    client_name: str
    client_contact: str
    project_title: str
    requested_services: tuple[str, ...]
    estimated_hours: int
    currency: str
    language: str = "en"
    notes: str = ""
    attachments: tuple[str, ...] = ()


@dataclass(frozen=True)
class ActionPayload:
    """Immutable external action payload bound to a SHA-256 approval digest."""

    principal: str
    capability: str
    connector: str
    recipient: str
    content: str
    parameters: dict[str, Any]
    attachments: tuple[str, ...]
    budget_amount: str
    budget_currency: str
    expires_at: int


@dataclass
class ApprovalToken:
    """Cryptographically bound human approval record."""

    token_id: str
    run_id: str
    action_digest: str
    principal: str
    decision: ApprovalDecision
    created_at: int
    expires_at: int
    consumed: bool = False
    revoked: bool = False
    revision_notes: str = ""


@dataclass(frozen=True)
class ProposalDraft:
    """Structured proposal/quote draft generated by the workflow."""

    run_id: str
    pack_id: str
    client_name: str
    project_title: str
    currency: str
    line_items: tuple[dict[str, Any], ...]
    total_amount: str
    missing_fields: tuple[str, ...]
    rendered_proposal: str
    is_draft: bool = True
    is_sample_data: bool = True


@dataclass(frozen=True)
class UsageRecord:
    """Honest usage and cost record."""

    event_id: str
    run_id: str
    attempt: int
    stage: UsageStage
    provider: str
    model: str
    tokens: int | None
    tool_fee: str | None
    amount: str | None
    currency: str
    payer: str
    pricing_source: str
    created_at: int
