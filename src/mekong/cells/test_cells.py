class TestParseRecommendation:
    def test_parse_valid_output(self) -> None:
        """A complete valid dict converts to ``CellRecommendation``."""
        raw = {
            "recommendation": "Increase marketing budget by 15%",
            "confidence": 0.85,
            "rationale": "ROI analysis shows diminishing returns at current spend",
            "risk_factors": ["Budget overrun", "Channel saturation"],
            "estimated_impact": "high",
        }
        result = _parse_recommendation(raw)
        assert isinstance(result, CellRecommendation)
        assert result.recommendation == "Increase marketing budget by 15%"
        assert result.confidence == 0.85
        assert "Budget overrun" in result.risk_factors
