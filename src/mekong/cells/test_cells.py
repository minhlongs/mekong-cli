class TestFindCellConfigs:
    def test_find_cell_configs(self, tmp_path: Path) -> None:
        """Enumerate cell YAML files in a particle's ``cells/`` subdirectory."""
        particle_dir = tmp_path / "particle"
        cells_dir = particle_dir / "cells"
        cells_dir.mkdir(parents=True)

        (cells_dir / "strategist.yaml").write_text(yaml.dump({
            "role": "strategist", "model": "claude-sonnet-4",
        }), encoding="utf-8")
        (cells_dir / "compliance.yaml").write_text(yaml.dump({
            "role": "compliance", "model": "claude-haiku-4-5",
        }), encoding="utf-8")

        configs = find_cell_configs(particle_dir)
        assert len(configs) == 2
        assert configs[0]["role"] == "compliance"  # sorted
        assert configs[1]["role"] == "strategist"
        assert "_path" in configs[0]

    def test_find_cell_configs_no_cells_dir(self, tmp_path: Path) -> None:
        """Particle without ``cells/`` returns empty list."""
        particle_dir = tmp_path / "empty-particle"
        particle_dir.mkdir()
        assert find_cell_configs(particle_dir) == []

    def test_find_cell_configs_invalid_yaml_skipped(self, tmp_path: Path) -> None:
        """Invalid YAML files in ``cells/`` are silently skipped."""
        particle_dir = tmp_path / "particle"
        cells_dir = particle_dir / "cells"
        cells_dir.mkdir(parents=True)

        (cells_dir / "good.yaml").write_text(yaml.dump({
            "role": "scout", "model": "gpt-4o",
        }), encoding="utf-8")
        # Unclosed bracket causes a YAML scanner error
        (cells_dir / "bad.yaml").write_text("unmatched: [bracket", encoding="utf-8")

        configs = find_cell_configs(particle_dir)
        assert len(configs) == 1
        assert configs[0]["role"] == "scout"


