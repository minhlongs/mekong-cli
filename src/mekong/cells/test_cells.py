class TestLoadConfig:
    def test_load_config_valid(self, valid_yaml: str, tmp_path: Path) -> None:
        """A valid YAML file loads into a ``CellConfig`` with correct fields."""
        config_path = tmp_path / "cell.yaml"
        config_path.write_text(valid_yaml, encoding="utf-8")

        config = load_cell_config(config_path)

        assert config.role == "strategist"
        assert config.model == "anthropic/claude-sonnet-4"
        assert config.capabilities == ["analysis", "recommendation"]
        assert config.privileges.max_budget == 100.0
        assert config.privileges.requires_approval is False
        assert config.boundaries.read == ["particle/*"]
        assert config.boundaries.write == ["particle/reports/*"]

    def test_load_config_missing_field(self, tmp_path: Path) -> None:
        """YAML missing ``model`` raises ``ValueError``."""
        data = {"role": "strategist"}  # missing model
        config_path = tmp_path / "missing.yaml"
        config_path.write_text(yaml.dump(data), encoding="utf-8")

        with pytest.raises(ValueError, match="missing required field"):
            load_cell_config(config_path)

    def test_load_config_missing_required_both(self, tmp_path: Path) -> None:
        """YAML missing both required fields raises ``ValueError``."""
        config_path = tmp_path / "empty.yaml"
        config_path.write_text(yaml.dump({"capabilities": []}), encoding="utf-8")

        with pytest.raises(ValueError, match="model.*role|role.*model"):
            load_cell_config(config_path)

    def test_load_config_nonexistent(self) -> None:
        """Loading a non-existent file raises ``FileNotFoundError``."""
        with pytest.raises(FileNotFoundError):
            load_cell_config("/nonexistent/path/cell.yaml")

    def test_load_config_invalid_yaml(self, tmp_path: Path) -> None:
        """Malformed YAML raises ``ValueError``."""
        config_path = tmp_path / "bad.yaml"
        config_path.write_text(": : invalid yaml [[[", encoding="utf-8")

        with pytest.raises(ValueError, match="Invalid YAML"):
            load_cell_config(config_path)

    def test_load_config_not_a_mapping(self, tmp_path: Path) -> None:
        """YAML that is not a dict raises ``ValueError``."""
        config_path = tmp_path / "scalar.yaml"
        config_path.write_text(yaml.dump("just a string"), encoding="utf-8")

        with pytest.raises(ValueError, match="must be a YAML mapping"):
            load_cell_config(config_path)

    def test_load_config_minimal(self, tmp_path: Path) -> None:
        """Minimal valid config (only required fields) loads without error."""
        data = {"role": "observer", "model": "gpt-4o-mini"}
        config_path = tmp_path / "minimal.yaml"
        config_path.write_text(yaml.dump(data), encoding="utf-8")

        config = load_cell_config(config_path)
        assert config.role == "observer"
        assert config.model == "gpt-4o-mini"
        assert config.capabilities == []
        assert config.privileges.max_budget == 0.0
        assert config.privileges.requires_approval is False


