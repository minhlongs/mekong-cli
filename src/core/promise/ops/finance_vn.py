VND_MAX = 1_000_000_000_000  # 1.000 tỷ đồng — beyond any OPC-scale input


def _money(description: str, maximum: int = VND_MAX) -> dict[str, object]:
    return {"type": "number", "minimum": 0, "maximum": maximum, "description": description}


def _period(description: str = "Tax/payroll period the calculation applies to (YYYY-MM-DD or YYYY-MM)") -> dict[str, object]:
    return {"type": "string", "format": "date", "description": description}


