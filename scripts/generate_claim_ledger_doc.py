"""Regenerate ``docs/cli-promise/CLAIM_LEDGER.md`` from measured sources.

The public product promise (https://www.mekongmind.com/cli) advertises 197 command
groups. ``src/registry/capability_ledger.json`` is the frozen snapshot of that
promise — the denominator. This script joins the snapshot against the operation
registry in ``src/core/promise/ops/`` so the document states, per claim:

* which executable operations are bound (op_id, handler, postconditions),
* whether the command is EXECUTABLE or NOT_IMPLEMENTED *today*,
* which test is the acceptance proof for the binding.

Nothing here is hand-maintained: a claim that loses its binding shows up as
NOT_IMPLEMENTED on the next run instead of silently keeping a green row.

Usage::

    python scripts/generate_claim_ledger_doc.py [--check]

``--check`` exits non-zero when the committed document differs from the
regenerated one (used by CI to keep the ledger honest).
"""

from __future__ import annotations

import argparse
import collections
import pathlib
import sys

REPO_ROOT = pathlib.Path(__file__).resolve().parents[1]
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

from src.core.capability_ledger import CapabilityLedger
from src.core.promise.contracts import load_default_registry

DOC_PATH = REPO_ROOT / "docs" / "cli-promise" / "CLAIM_LEDGER.md"
DISPLAY_SOURCE = "https://www.mekongmind.com/cli"

DEPARTMENT_TITLES = {
    "ceo-command": "A — C-Suite Command (CEO/COO/CFO/CTO…)",
    "market-intelligence": "Market Intelligence",
    "product-strategy": "Product & Strategy",
    "engineering-factory": "B — Autonomous SDRC / Engineering Factory",
    "quality-compliance": "Quality & Compliance",
    "platform-operations": "Platform Operations",
    "growth-marketing": "Growth & Marketing",
    "sales-revenue": "C — Business Department Ops / Sales & Revenue",
    "customer-success": "Customer Success",
    "knowledge-memory": "Knowledge & Memory",
}


def build_document() -> str:
    ledger = CapabilityLedger()
    registry = load_default_registry()
    claims = ledger.list_all()

    ops_by_command: dict[str, list] = collections.defaultdict(list)
    for spec in registry.all():
        ops_by_command[spec.command].append(spec)

    integrity = ledger.validate_integrity()
    stats = ledger.get_summary_stats()
    executable = {name for name, ops in ops_by_command.items() if ops}
    unbound = [c["name"] for c in claims if c["name"] not in executable]

    lines: list[str] = []
    add = lines.append

    add("# Claim Ledger — advertised promise → executable binding → proof")
    add("")
    add("> Generated by `python scripts/generate_claim_ledger_doc.py`. **Do not edit by hand.**")
    add(f"> Sources: `src/registry/capability_ledger.json` (frozen snapshot of {DISPLAY_SOURCE})")
    add("> and the operation registry in `src/core/promise/ops/`.")
    add("")
    add("## How to read this document")
    add("")
    add(f"The denominator is the advertised snapshot: **{len(claims)} command groups**. Claims are")
    add("never deleted, merged or re-worded to improve a ratio — a claim that has no executable")
    add("operation is reported as `NOT_IMPLEMENTED` here, in `GET /v1/cli/capabilities` and at")
    add("runtime (`NO_OPERATION_BINDING`), and the milestone gates stay unmet until the business")
    add("condition is measured from persisted facts.")
    add("")
    add("Column meanings:")
    add("")
    add("- **execution** — `EXECUTABLE` when at least one `OperationSpec` is bound to the command")
    add("  (schema validation → job → real handler → postconditions → evidence → signed receipt);")
    add("  `NOT_IMPLEMENTED` when the command is advertised but has no bound operation yet.")
    add("- **bound operations** — `op_id`s reachable through `mekong <command> <subcommand>` and")
    add("  `POST /v1/cli/runs`.")
    add("- **proof** — the test that asserts the business result of the binding. A claim without a")
    add("  proof test is not accepted as complete, whatever its HTTP status code says.")
    add("- **sample_output in the ledger is documentation only** — it is never used as evidence of a")
    add("  run (see `docs/cli-promise/STATUS.md`).")
    add("")
    add("## Measured summary")
    add("")
    add("| measure | value |")
    add("| --- | --- |")
    add(f"| advertised command groups (denominator) | {len(claims)} |")
    add(f"| ledger integrity valid | {integrity['valid']} |")
    add(f"| commands with a bound operation | {len(executable & {c['name'] for c in claims})} |")
    add(f"| advertised commands still NOT_IMPLEMENTED | {len(unbound)} |")
    add(f"| bound operations (`OperationSpec`) | {len(registry)} |")
    add(f"| operations with an acceptance test | {sum(1 for s in registry.all() if s.test_id)} |")
    add(f"| clusters | {len(stats['by_cluster'])} |")
    add(f"| departments | {len(stats['by_department'])} |")
    add(f"| layers (L0–L5) | {len(stats['by_layer'])} |")
    add(f"| maturity tiers declared | {', '.join(sorted(stats['by_maturity_tier']))} |")
    add("")
    add("### Claims by department and execution status")
    add("")
    add("| department | claims | executable | not implemented |")
    add("| --- | --- | --- | --- |")
    by_dept: dict[str, list] = collections.defaultdict(list)
    for claim in claims:
        by_dept[claim["department_id"]].append(claim)
    for dept in sorted(by_dept, key=lambda d: (-len(by_dept[d]), d)):
        rows = by_dept[dept]
        bound = sum(1 for c in rows if c["name"] in executable)
        add(f"| `{dept}` — {DEPARTMENT_TITLES.get(dept, dept)} | {len(rows)} | {bound} "
            f"| {len(rows) - bound} |")
    add("")
    add("### Claims by layer and gate artifact")
    add("")
    add("| layer | claims | gate artifact |")
    add("| --- | --- | --- |")
    gate_by_layer: dict[str, collections.Counter] = collections.defaultdict(collections.Counter)
    for claim in claims:
        gate_by_layer[claim["layer_id"]][claim.get("gate_artifact") or "—"] += 1
    for layer in sorted(gate_by_layer):
        total = sum(gate_by_layer[layer].values())
        artifacts = ", ".join(f"`{g}` ×{n}" for g, n in sorted(gate_by_layer[layer].items()))
        add(f"| {layer} | {total} | {artifacts} |")
    add("")
    add("## Per-claim binding matrix")
    add("")
    for dept in sorted(by_dept, key=lambda d: (-len(by_dept[d]), d)):
        rows = by_dept[dept]
        bound_count = sum(1 for c in rows if c["name"] in executable)
        add(f"### `{dept}` — {DEPARTMENT_TITLES.get(dept, dept)} ({len(rows)} claims, "
            f"{bound_count} executable)")
        add("")
        add("| claim_id | command | layer | gate | execution | bound operations | proof |")
        add("| --- | --- | --- | --- | --- | --- | --- |")
        for claim in sorted(rows, key=lambda c: c["claim_id"]):
            name = claim["name"]
            ops = ops_by_command.get(name, [])
            execution = "EXECUTABLE" if ops else "**NOT_IMPLEMENTED**"
            op_cell = "<br>".join(f"`{o.op_id}`" for o in ops) or "—"
            proof = "<br>".join(f"`{o.test_id}`" for o in ops if o.test_id) or "—"
            gate = claim.get("gate_id") or "—"
            add(f"| `{claim['claim_id']}` | `mekong {name}` | {claim['layer_id']} | `{gate}` "
                f"| {execution} | {op_cell} | {proof} |")
        add("")

    if unbound:
        add("## Outstanding: advertised commands without a bound operation")
        add("")
        add("These claims stay in the denominator. Each one is answered at runtime with")
        add("`NOT_IMPLEMENTED` / `NO_OPERATION_BOUND` — never with a synthetic success — and each")
        add("needs an `OperationSpec` (schema, handler, effects, postconditions, proof test)")
        add("before it may be counted as delivered.")
        add("")
        for chunk_start in range(0, len(unbound), 8):
            add("- " + ", ".join(f"`{n}`" for n in unbound[chunk_start:chunk_start + 8]))
        add("")

    add("---")
    add("")
    add("Progress, remaining gaps and the wave plan live in `docs/cli-promise/STATUS.md`.")
    add("")
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true",
                        help="fail when the committed document is out of date")
    args = parser.parse_args()

    document = build_document()
    if args.check:
        current = DOC_PATH.read_text(encoding="utf-8") if DOC_PATH.exists() else ""
        if current != document:
            print(f"{DOC_PATH.relative_to(REPO_ROOT)} is out of date — "
                  "run: python scripts/generate_claim_ledger_doc.py")
            return 1
        print(f"{DOC_PATH.relative_to(REPO_ROOT)} is up to date")
        return 0

    DOC_PATH.parent.mkdir(parents=True, exist_ok=True)
    DOC_PATH.write_text(document, encoding="utf-8")
    print(f"wrote {DOC_PATH.relative_to(REPO_ROOT)} ({len(document.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
